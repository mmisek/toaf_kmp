        }
        return result
    }

    override suspend fun readCoding(): List<ByteArray>? {
        val result: MutableList<ByteArray> = ArrayList()
        for (i in 0..0xf) {
            val block = readCodingBlock(i) ?: return null
            result.add(block)
        }
        return result
    }

    // Wg SGBD C_C_LESEN: 08 <blok>, dane od [4] ([3] = echo bloku)
    private suspend fun readCodingBlock(block: Int): ByteArray? {
        val message = interfaceWrite(byteArrayOf(0x08, block.toByte()), 300)
        try {
            if (message.isValid)
                return message.answer.copyOfRange(4, message.answer.size - 1)
        } catch (ex: CancellationException) {
            throw ex
        } catch (ex : Exception)
        {
            Logger.e {"$tag [readCoding], $ex, $message"}
        }
        return null
    }

    override suspend fun writeCoding(dataToSave: List<ByteArray>): Boolean {
        if (dataToSave.size != 0x10) return false
        for (i in dataToSave.indices) {
            val block = dataToSave[i]
            val payload = if (i == 0x0F)
                block + block.fold(0) { acc, b -> acc xor (b.toInt() and 0xFF) }.toByte()
            else block
            var written = false
            for (attempt in 0..2) {
                if (interfaceWrite(byteArrayOf(0x09, i.toByte()) + payload, 200).isValid &&
                    readCodingBlock(i)?.contentEquals(block) == true) {
                    written = true
                    break
                }
            }
            if (!written) {
                Logger.e { "$tag [writeCoding], block $i write/verify failed" }
                return false
            }
        }
        return true
    }

    override fun getVinLength(): Int = 7

    override suspend fun writeVIN(newVin: String): Boolean {
        val vinBytes = newVin.toByteArray()
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x5F, 0x00)).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x60, 0x0C)).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x61, 0x00)).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x62, 0x05)).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x3F, vinBytes[0])).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x40, vinBytes[1])).isValid) return false
        for (i in 0..2) {
            val x = newVin.substring(2 + 2 * i, 4 + 2 * i).toInt(16)
            if (!interfaceWrite(
                    byteArrayOf(
                        0x07,
                        0x01,
                        (0x41 + i).toByte(),
                        x.toByte()
                    )
                ).isValid
            ) return false
        }
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x3C, 0xFF.toByte())).isValid) return false
        return interfaceWrite(byteArrayOf(0x07, 0x01, 0x33, 0x10)).isValid
    }

    override suspend fun writeOdometer(odometer: Long): Boolean {
        if (odometer < 0 || odometer / 100 > 0xFFFF) return false
        val newOdo = odometer/100
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x5F, 0x00)).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x60, 0x11)).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x61, 0x00)).isValid) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x62, 0x02)).isValid) return false
        if (!interfaceWrite(
                byteArrayOf(
                    0x07,
                    0x01,
                    0x3F,
                    ((newOdo and 0xFF00L) shr 8).toByte()
                )
            ).isValid
        ) return false
        if (!interfaceWrite(
                byteArrayOf(
                    0x07,
                    0x01,
                    0x40,
                    (newOdo and 0x00FFL).toByte()
                )
            ).isValid
        ) return false
        if (!interfaceWrite(byteArrayOf(0x07, 0x01, 0x3C, 0xFF.toByte())).isValid) return false
        return interfaceWrite(byteArrayOf(0x07, 0x01, 0x33, 0x10)).isValid
    }

    override fun detectAutoLightMode(coding: List<ByteArray>?): Int {
        if (coding != null) {
            if (coding.size == 0x10) {
                for (i in autoLightsModes.indices) {
                    var correct = true
                    for (j in 2 until autoLightsModes[i].size - 1) {
                        val t1 = coding[j]
                        val t2 = autoLightsModes[i][j - 1]
                        if (!t1.contentEquals(t2)) {
                            correct = false
                            break
                        }
                    }
                    if (correct) return i
                }
            }
        }
        return 0
    }

    override fun setAutoLightMode(coding: List<ByteArray>, mode: Int): List<ByteArray> {
        require(coding.size == 0x10 && coding[0].size > 0x12) { "Invalid LSM coding" }
        require(mode in autoLightsModes.indices) { "Invalid auto light mode: $mode" }
        val newCoding = coding.map { it.copyOf() }.toMutableList()
        if (mode == 1) {
            newCoding[0][0x04] = (newCoding[0][0x04].toInt() or 0x80 or 0x02).toByte()
            newCoding[0][0x12] = (newCoding[0][0x12].toInt() or 0x2A).toByte()
        } else {
            newCoding[0][0x04] = (newCoding[0][0x04].toInt() and (0x80 or 0x02).inv()).toByte()
            newCoding[0][0x12] = (newCoding[0][0x12].toInt() and 0x2A.inv()).toByte()
        }
        val autoLights = autoLightsModes[mode]
        for (i in autoLights.indices) newCoding[i + 1] = autoLights[i].copyOf()
        return newCoding
    }

    private suspend fun policeLightsSwitch(): Boolean {
        val coding = readCodingBlock(0x00) ?: return false
        if (coding.size <= 0x03) return false
        coding[0x03] = (coding[0x03].toInt() xor (0x01)).toByte()
        return interfaceWrite(byteArrayOf(0x09, 0x00) + coding).isValid &&
                readCodingBlock(0x00)?.contentEquals(coding) == true
    }
