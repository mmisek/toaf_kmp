    override suspend fun control(controlElement: ControlElement): Boolean {
        when (controlElement.block) {
            0x00 -> {
                val data = byteArrayOf(0x0C, 0x00, 0x00, 0xF0.toByte(), 0xF0.toByte(), 0x00, 0x00, 0x00,
                    0x80.toByte(), 0x00, 0x00, 0x80.toByte(), 0x00, 0x00, 0x00, 0x00)
                val status = interfaceWrite(byteArrayOf(0x0B))
                if (status.isValid && status.answer.size > 0x13) {
                    data[1 + 7] = status.answer[0x0A]
                    data[1 + 9] = status.answer[0x12]
                    data[1 + 10] = status.answer[0x13]
                }
                if (interfaceWrite(data).isValid) {
                    //control selected element
                    if (controlElement.controlSetValue != null) data[controlElement.byteInBlock + 1] =
                        controlElement.controlSetValue!!.value.toByte()
                    else data[controlElement.byteInBlock + 1] = controlElement.value.toByte()

                    return (interfaceWrite(data).isValid)
                }
            }

            0x01 -> return interfaceWrite(byteArrayOf(0x1C.toByte(), 0xFF.toByte())).isValid
            0x02 -> return policeLightsSwitch()
            else -> {}
        }
        return false
    }

    override suspend fun getVIN(): String? {
        val message = interfaceWrite(byteArrayOf(0x02, 0x02))
        if (message.isValid) {
            try {
                val vin = String(message.answer.copyOfRange(4, 6)) +
                        String.format(
                            "%02X%02X%02X",
                            message.answer[6].toInt() and 0xFF,
                            message.answer[7].toInt() and 0xFF,
                            message.answer[8].toInt() and 0xFF
                        )
                return vin
            } catch (ex: CancellationException) {
                throw ex
            } catch (ex: Exception) {
                Logger.e {"$tag [getVIN], $ex, $message"}
                return null
            }
        }
        return null
    }
