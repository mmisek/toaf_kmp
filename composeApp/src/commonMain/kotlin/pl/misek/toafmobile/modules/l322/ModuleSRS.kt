    private suspend fun login(): Boolean {
        var res = interfaceWrite(byteArrayOf(0x90.toByte(), 0xFF.toByte(), 0xFF.toByte())).isValid
        delay(1000)
        res = res && interfaceWrite(byteArrayOf(0x95.toByte(), 0x12, 0x03, 0x08, 0x32)).isValid
        return res
    }

    private suspend fun getProgrammingDate(): String {
        if (login())
        {
            val message = interfaceWrite(byteArrayOf(0x08, 0x02))
            try {
                if (message.isValid) {
                    val answer = message.answer
                    return String.format("%02d%02d%02d", answer[5], answer[6], answer[7])
                }
            } catch (ex: CancellationException) {
                throw ex
            } catch (ex : Exception)
            {
                Logger.e {"$tag [getProgrammingDate()], $ex, $message"}
            }
        }
        return ""
    }

    private suspend fun getSerialNumber(): String {
        if (login()) {
            val message = interfaceWrite(byteArrayOf(0x08, 0x03))
            try {
                if (message.isValid) {
                    return String(message.answer.copyOfRange(6, message.answer.size))
                }
            } catch (ex: CancellationException) {
                throw ex
            } catch (ex : Exception)
            {
                Logger.e {"$tag [getSErialNumber], $ex, $message"}
            }
        }
        return ""
    }

    override suspend fun getVIN(): String {
        if (login()) {
            val message = interfaceWrite(byteArrayOf(0x08.toByte(), 0x03))
            try{
                if (message.isValid) {
                    val answer = message.answer
                    return String.format(
                        "%c%c%02X%02X%02X",
                        answer[4], answer[5], answer[6], answer[7], answer[8]
                    )
                }
            } catch (ex: CancellationException) {
                throw ex
            } catch (ex : Exception)
            {
                Logger.e {"$tag [getVIN], $ex, $message"}
            }
        }
        return ""
    }

    override suspend fun getAllErrors(): List<ModuleError>? {
        var result: MutableList<ModuleError>? = null
        if (login()) {
            for (i in 0..4) {
                val message = interfaceWrite(byteArrayOf(0x05, i.toByte()))
                try {
                    if (message.isValid) {
                        result = ArrayList()
                        val errorCode =
                            ((message.answer[6 + 3 * i].toInt() and 0xFF) shl 8) + (message.answer[7 + 3 * i].toInt() and 0xFF)
                        val errorDescription: MutableList<Pair<StringResource, Any?>> = ArrayList()
                        if ((message.answer[8 + 3 * i].toInt() and 0xFF) == 0x00) errorDescription.add(
                            Pair(Res.string.srs_error_detail_00, null)
                        )
                        else {
                            for (k in 0..7) {
                                val number = message.answer[8 + 3 * i].toInt() and (0x01 shl k)
                                if (number == (0x01 shl k)) {
                                    ResourceMapper
                                        .stringResource(
                                            String.format(
                                                "srs_error_detail_%02X",
                                                number
                                            )
                                        )
                                        ?.let { errorDescription.add(Pair(it, null)) }
                                }
                            }
                            result.add(
                                ModuleError(
                                    ModuleAddress.MODULE_SRS,
                                    String.format("%04X", errorCode),
                                    errorDescription
                                )
                            )
                        }
                    }
                } catch (ex: CancellationException) {
                    throw ex
                } catch (ex : Exception)
                {
                    Logger.e {"$tag [getAllErros], $ex, $message"}
                }
            }
            this.reset()
        }

        return result
    }

    override suspend fun clearAllErrors(): Boolean {
        if (securityAccess05()) {
            val message = interfaceWrite(0x14.toByte(), byteArrayOf(0x00, 0x00), 1500)
            this.reset()
            return message.isValid
        }
        return false
    }

    override suspend fun reset(): Boolean  = interfaceWrite(0x11.toByte(), byteArrayOf()).isValid

    override suspend fun readCoding(): List<ByteArray>? {
        var result: MutableList<ByteArray>? = null
        var i = 1

        var message: OBDMessage
        if (login()) {
            do {
                message =  interfaceWrite(byteArrayOf(0x08, i++.toByte()))
                try {
                    if (message.isValid) {
                        if (result == null) result = ArrayList()
                        result.add(message.answer.copyOfRange(4, message.answer.size - 1))
                    } else if (result != null) {
                        return result.ifEmpty { null }
                    }
                } catch (ex: CancellationException) {
                    throw ex
                } catch (ex : Exception)
                {
                    Logger.e {"$tag [radCoding], $ex, $message"}
                }
            } while (message.isValid)
        }
        return result
    }

    override suspend fun writeCoding(dataToSave: List<ByteArray>): Boolean {
        for (i in dataToSave.indices) {
            val message = interfaceWrite(arrayOf(byteArrayOf(0x09,i.toByte()), dataToSave[i]))
            if (!message.isValid) return false
        }
        return true
    }

    private suspend fun testerPresent(): Boolean  =  interfaceWrite(0x3E.toByte(), byteArrayOf()).isValid

    private suspend fun securityAccess05(): Boolean {
        val level = 0x05.toByte()
        if (testerPresent()) {
            var message =  interfaceWrite(0x10.toByte(), byteArrayOf(0x85.toByte()))
            try {
                if (message.isValid) {
                    message = interfaceWrite(0x27.toByte(), byteArrayOf(level), 500)
                    if (message.isValid) {
                        val code =
                            ((message.answer[6].toInt() and 0xFF) shl 8) + (message.answer[7].toInt() and 0xFF)
                        if (code == 0x0000) return true
                        else {
                            val seed = securityAccessCalculator(code)
                            val data = byteArrayOf(
                                (level + 1).toByte(),
                                ((seed and 0xFF00) shr 8).toByte(), (seed and 0xFF).toByte()
                            )
                            return interfaceWrite(0x27.toByte(), data).isValid
                        }
                    }
                }
            } catch (ex: CancellationException) {
                throw ex
            } catch (ex : Exception)
            {
                Logger.e {"$tag [securityAccess], $ex,$message"}
            }
        }

        return false
    }

    private fun securityAccessCalculator(inputKey: Int): Int {
        var key = inputKey
        var n = key shr 8
        n = n xor 0x57
        n = n and 0x07
        n += 3
        for (i in 0 until n) {
            var x = 0
            if ((key and 0x2000) == 0x2000) x = x xor 1
            if ((key and 0x1000) == 0x1000) x = x xor 1
            if ((key and 0x0020) == 0x0020) x = x xor 1
            if ((key and 0x0004) == 0x0004) x = x xor 1
            if ((key and 0x0001) == 0x0001) x = x xor 1
            key = key shl 1
            key = key and 0xFFFF
            key = key xor x
        }
        return key
    }

    override suspend fun readEeprom(address: Int, size: Int): ByteArray? {
        val message =  interfaceWrite(
        byteArrayOf(
            0x06,
            0x01,
            0x00,
            (0x0C + (address shr 8)).toByte(),
            (address and 0xFF).toByte(),
            size.toByte()
        )
        )
        try{
            return if (message.isValid) message.answer.copyOfRange(0x03, 3 + size) else null
        }
        catch (ex: CancellationException) {
            throw ex
        }
        catch (ex : Exception)
        {
            Logger.e {"$tag [readEeprom], $ex, $message"}
            return null
        }

    }

    override suspend fun writeEeprom(address: Int, data: ByteArray): Boolean {
        val dataToWrite =
        byteArrayOf(
            0x07,
            0x01,
            0x00,
            (0x0C + (address shr 8)).toByte(),
            (address and 0xFF).toByte(),
            (data.size).toByte()) + data
        return interfaceWrite(dataToWrite).isValid
    }

